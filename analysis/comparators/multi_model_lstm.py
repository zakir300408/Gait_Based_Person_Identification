"""Reproduce and transfer Tran et al.'s published Multi-Model LSTM.

The model class is imported from the authors' repository.  WHU-Gait segments
are generated by their MATLAB script from Dataset #3.  Treadmill windows are
adapted only by temporal resampling to the published 80-sample input length.
"""

from __future__ import annotations

import copy
import json
import random
from collections import defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path
from time import perf_counter

import numpy as np
import pandas as pd
import torch
import torch.nn.functional as functional
from sklearn.metrics import accuracy_score, f1_score
from sklearn.model_selection import train_test_split
from torch.utils.data import DataLoader, TensorDataset

from analysis.comparators.common import (
    majority_vote_trial_rows,
    resample_time,
)


ROOT = Path(__file__).resolve().parents[2]
CONFIG_PATH = Path(__file__).with_name("multi_model_lstm.json")
from LSTM_Pthon.authen_netw import LSTM_6Chan_OU


MODEL_NAME = "Multi-Model LSTM"
MODEL_KEY = "multi_model_lstm_official"
SOURCE = "https://github.com/halam189/Gait_Recognition_LSTM"
CONDITIONS = (
    "fpa_large",
    "fpa_small",
    "step_width_large",
    "step_width_small",
    "trunk_sway_large",
    "trunk_sway_small",
    "walk_speed_large",
    "walk_speed_small",
    "dual_task",
)


@dataclass(frozen=True)
class Settings:
    seed: int
    input_group_size: int
    published_paper_input_group_size: int
    hidden_size: int
    layers: int
    learning_rate: float
    momentum: float
    train_batch_size: int
    test_batch_size: int
    max_epochs: int
    early_stopping_patience: int
    validation_fraction_treadmill: float
    published_whugait_accuracy_percent: float
    admission_tolerance_percentage_points: float
    official_segment_root: Path
    treadmill_h5: Path
    output_root: Path
    treadmill_output: Path
    run_whugait: bool
    run_treadmill_after_admission: bool


def load_settings() -> Settings:
    values = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    for key in (
        "official_segment_root",
        "treadmill_h5",
        "output_root",
        "treadmill_output",
    ):
        values[key] = ROOT / values[key]
    return Settings(**values)


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def locate_official_segments(root: Path) -> dict[str, Path]:
    matches = {}
    for partition, suffix in (
        ("train", "Train"),
        ("validation", "Vali"),
        ("test", "Test"),
    ):
        candidates = sorted(root.glob(f"*WHU_equal_118*{suffix}"))
        if len(candidates) != 1:
            raise FileNotFoundError(
                f"expected one authors' WHU {partition} segment file, found {candidates}"
            )
        matches[partition] = candidates[0]
    return matches


def load_segment_matrix(path: Path, cache_root: Path) -> tuple[np.ndarray, np.ndarray]:
    cache_root.mkdir(parents=True, exist_ok=True)
    input_cache = cache_root / f"{path.name}.inputs.npy"
    label_cache = cache_root / f"{path.name}.labels.npy"
    if input_cache.is_file() and label_cache.is_file():
        return np.load(input_cache, mmap_mode="r"), np.load(label_cache, mmap_mode="r")
    matrix = np.loadtxt(path, dtype=np.float32)
    if matrix.ndim != 2 or matrix.shape[1] != 481:
        raise ValueError(f"invalid authors' segment matrix {path}: {matrix.shape}")
    inputs = np.ascontiguousarray(matrix[:, :480], dtype=np.float32)
    labels = np.ascontiguousarray(matrix[:, -1], dtype=np.int64)
    np.save(input_cache, inputs)
    np.save(label_cache, labels)
    return np.load(input_cache, mmap_mode="r"), np.load(label_cache, mmap_mode="r")


def make_loader(
    inputs: np.ndarray,
    labels: np.ndarray,
    batch_size: int,
    shuffle: bool,
) -> DataLoader:
    dataset = TensorDataset(
        torch.from_numpy(np.asarray(inputs)),
        torch.from_numpy(np.asarray(labels, dtype=np.int64)),
    )
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=0,
        pin_memory=torch.cuda.is_available(),
    )


def build_model(classes: int, settings: Settings) -> LSTM_6Chan_OU:
    return LSTM_6Chan_OU(
        settings.input_group_size,
        settings.hidden_size,
        settings.layers,
        classes,
        segment_length=80,
    )


def evaluate(
    model: LSTM_6Chan_OU,
    loader: DataLoader,
    device: torch.device,
) -> tuple[np.ndarray, np.ndarray, float]:
    model.eval()
    truth = []
    prediction = []
    loss_sum = 0.0
    with torch.no_grad():
        for inputs, labels in loader:
            inputs = inputs.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)
            output, _ = model(inputs)
            loss_sum += float(functional.nll_loss(output, labels, reduction="sum").cpu())
            truth.append(labels.cpu().numpy())
            prediction.append(output.argmax(dim=1).cpu().numpy())
    true_array = np.concatenate(truth)
    prediction_array = np.concatenate(prediction)
    return true_array, prediction_array, loss_sum / len(true_array)


def train_model(
    model: LSTM_6Chan_OU,
    train_loader: DataLoader,
    validation_loader: DataLoader,
    settings: Settings,
    device: torch.device,
) -> tuple[LSTM_6Chan_OU, pd.DataFrame]:
    model = model.to(device)
    optimizer = torch.optim.SGD(
        model.parameters(),
        lr=settings.learning_rate,
        momentum=settings.momentum,
    )
    best_loss = float("inf")
    best_state = copy.deepcopy(model.state_dict())
    stale_epochs = 0
    history = []
    for epoch in range(1, settings.max_epochs + 1):
        model.train()
        training_loss = 0.0
        observations = 0
        for inputs, labels in train_loader:
            inputs = inputs.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)
            optimizer.zero_grad(set_to_none=True)
            output, _ = model(inputs)
            loss = functional.nll_loss(output, labels)
            loss.backward()
            optimizer.step()
            training_loss += float(loss.detach().cpu()) * len(labels)
            observations += len(labels)
        validation_truth, validation_prediction, validation_loss = evaluate(
            model, validation_loader, device
        )
        validation_accuracy = accuracy_score(
            validation_truth, validation_prediction
        )
        row = {
            "epoch": epoch,
            "train_loss": training_loss / observations,
            "validation_loss": validation_loss,
            "validation_accuracy": validation_accuracy,
        }
        history.append(row)
        print(
            f"[{MODEL_NAME} epoch {epoch:03d}] "
            f"loss={row['train_loss']:.6f} "
            f"val_loss={validation_loss:.6f} "
            f"val_acc={validation_accuracy:.6f}",
            flush=True,
        )
        if validation_loss < best_loss:
            best_loss = validation_loss
            best_state = copy.deepcopy(model.state_dict())
            stale_epochs = 0
        else:
            stale_epochs += 1
            if stale_epochs >= settings.early_stopping_patience:
                break
    model.load_state_dict(best_state)
    return model, pd.DataFrame(history)


def run_whugait(settings: Settings) -> dict:
    settings.output_root.mkdir(parents=True, exist_ok=True)
    set_seed(settings.seed)
    segment_paths = locate_official_segments(settings.official_segment_root)
    cache_root = settings.output_root / "segment_cache"
    x_train, y_train = load_segment_matrix(segment_paths["train"], cache_root)
    x_validation, y_validation = load_segment_matrix(
        segment_paths["validation"], cache_root
    )
    x_test, y_test = load_segment_matrix(segment_paths["test"], cache_root)
    train_loader = make_loader(
        x_train, y_train, settings.train_batch_size, shuffle=True
    )
    validation_loader = make_loader(
        x_validation, y_validation, settings.test_batch_size, shuffle=False
    )
    test_loader = make_loader(
        x_test, y_test, settings.test_batch_size, shuffle=False
    )
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    started = perf_counter()
    model, history = train_model(
        build_model(118, settings),
        train_loader,
        validation_loader,
        settings,
        device,
    )
    truth, prediction, test_loss = evaluate(model, test_loader, device)
    accuracy_percent = 100.0 * accuracy_score(truth, prediction)
    difference = accuracy_percent - settings.published_whugait_accuracy_percent
    admitted = abs(difference) <= settings.admission_tolerance_percentage_points
    result = {
        "model": MODEL_NAME,
        "model_key": MODEL_KEY,
        "source": SOURCE,
        "torch_version": torch.__version__,
        "device": torch.cuda.get_device_name(0) if torch.cuda.is_available() else "CPU",
        "seed": settings.seed,
        "train_samples": int(len(y_train)),
        "validation_samples": int(len(y_validation)),
        "test_samples": int(len(y_test)),
        "epochs_completed": int(len(history)),
        "test_loss": test_loss,
        "published_accuracy_percent": settings.published_whugait_accuracy_percent,
        "measured_accuracy_percent": accuracy_percent,
        "difference_percentage_points": difference,
        "admission_tolerance_percentage_points": settings.admission_tolerance_percentage_points,
        "admitted": admitted,
        "elapsed_seconds": perf_counter() - started,
        "official_code_input_group_size": settings.input_group_size,
        "paper_stated_input_group_size": settings.published_paper_input_group_size,
        "protocol": (
            "Authors' MATLAB Dataset #3 reconstruction and segment files; "
            "authors' LSTM_6Chan_OU class; SGD 0.15, momentum 0.9; "
            "validation-loss early stopping"
        ),
    }
    history.to_csv(settings.output_root / "whugait_history.csv", index=False)
    pd.DataFrame({"truth": truth, "prediction": prediction}).to_csv(
        settings.output_root / "whugait_predictions.csv", index=False
    )
    torch.save(model.state_dict(), settings.output_root / "whugait_model.pt")
    (settings.output_root / "whugait_admission.json").write_text(
        json.dumps(result, indent=2), encoding="utf-8"
    )
    return result


def run_treadmill(settings: Settings) -> None:
    from analysis.prism_gait.hcgf import load_original_h5

    set_seed(settings.seed)
    data = load_original_h5(settings.treadmill_h5)
    x_all = resample_time(np.stack(data["x_train"]).astype(np.float32), 80)
    x_all = x_all.reshape(len(x_all), -1)
    y_all = np.asarray(data["y_train"], dtype=np.int64)
    train_indices, validation_indices = train_test_split(
        np.arange(len(y_all)),
        test_size=settings.validation_fraction_treadmill,
        random_state=settings.seed,
        stratify=y_all,
    )
    train_loader = make_loader(
        x_all[train_indices],
        y_all[train_indices],
        settings.train_batch_size,
        shuffle=True,
    )
    validation_loader = make_loader(
        x_all[validation_indices],
        y_all[validation_indices],
        settings.test_batch_size,
        shuffle=False,
    )
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model, history = train_model(
        build_model(int(np.max(y_all)) + 1, settings),
        train_loader,
        validation_loader,
        settings,
        device,
    )

    condition_rows = []
    subject_rows = []
    prediction_rows = []
    trial_details = []
    for condition in CONDITIONS:
        inputs = resample_time(
            np.stack(data["x_test_by_cond"][condition]).astype(np.float32),
            80,
        ).reshape(len(data["x_test_by_cond"][condition]), -1)
        truth = np.asarray(data["y_test_by_cond"][condition], dtype=np.int64)
        metadata = data["meta_test_by_cond"][condition]
        loader = make_loader(
            inputs, truth, settings.test_batch_size, shuffle=False
        )
        measured_truth, prediction, _ = evaluate(model, loader, device)
        if not np.array_equal(truth, measured_truth):
            raise ValueError("treadmill label order changed during evaluation")
        trial_summary, current_trials = majority_vote_trial_rows(
            MODEL_KEY, condition, truth, prediction, metadata
        )
        trial_details.extend(current_trials)
        condition_rows.append(
            {
                "model": MODEL_KEY,
                "display_name": MODEL_NAME,
                "condition": condition,
                "window_accuracy": float(accuracy_score(truth, prediction)),
                "window_macro_f1": float(f1_score(truth, prediction, average="macro")),
                "n_windows": int(len(truth)),
                **trial_summary,
                "input_length": 80,
                "normalization": "none",
                "source": SOURCE,
            }
        )
        per_subject: dict[str, list[int]] = defaultdict(list)
        for target, estimate, meta in zip(truth, prediction, metadata):
            subject = str(meta["subject"])
            per_subject[subject].append(int(target == estimate))
            prediction_rows.append(
                {
                    "model": MODEL_KEY,
                    "condition": condition,
                    "subject": subject,
                    "trial": str(meta["trial"]),
                    "truth": int(target),
                    "prediction": int(estimate),
                    "correct": int(target == estimate),
                }
            )
        for subject, correct in sorted(per_subject.items()):
            subject_rows.append(
                {
                    "model": MODEL_KEY,
                    "condition": condition,
                    "subject": subject,
                    "subject_window_accuracy": float(np.mean(correct)),
                    "n_windows": len(correct),
                }
            )

    settings.treadmill_output.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(condition_rows).to_csv(
        settings.treadmill_output / "official_treadmill_results.csv", index=False
    )
    pd.DataFrame(subject_rows).to_csv(
        settings.treadmill_output / "official_subject_condition_accuracy.csv",
        index=False,
    )
    pd.DataFrame(prediction_rows).to_csv(
        settings.treadmill_output / "official_window_predictions.csv", index=False
    )
    pd.DataFrame(trial_details).to_csv(
        settings.treadmill_output / "official_trial_predictions.csv", index=False
    )
    history.to_csv(settings.treadmill_output / "training_history.csv", index=False)
    torch.save(model.state_dict(), settings.treadmill_output / "treadmill_model.pt")
    audit = {
        "model": MODEL_NAME,
        "model_key": MODEL_KEY,
        "source": SOURCE,
        "architecture_modified": False,
        "input_adapter": "linear temporal resampling from 200 to 80 samples",
        "normalization": "none",
        "training_split": "stratified 90/10 split of treadmill enrollment windows",
        "paper_code_discrepancy": (
            "paper states input group K=4; released WHU script sets input_dim=5"
        ),
        "settings": {
            **asdict(settings),
            "official_segment_root": str(settings.official_segment_root),
            "treadmill_h5": str(settings.treadmill_h5),
            "output_root": str(settings.output_root),
            "treadmill_output": str(settings.treadmill_output),
        },
    }
    (settings.treadmill_output / "audit.json").write_text(
        json.dumps(audit, indent=2), encoding="utf-8"
    )


def main() -> None:
    settings = load_settings()
    admission = None
    if settings.run_whugait:
        admission = run_whugait(settings)
        print(json.dumps(admission, indent=2), flush=True)
    if settings.run_treadmill_after_admission:
        if admission is None:
            admission = json.loads(
                (settings.output_root / "whugait_admission.json").read_text(
                    encoding="utf-8"
                )
            )
        if not admission["admitted"]:
            raise RuntimeError(
                "Multi-Model LSTM did not pass the declared WHU-Gait admission gate"
            )
        run_treadmill(settings)


if __name__ == "__main__":
    main()
